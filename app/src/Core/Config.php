<?php
declare(strict_types=1);

namespace App\Core;

/**
 * Configuration lookup. Order of preference (first existing file wins):
 *  1. GRC_CONFIG_FILE environment variable
 *  2. <APP_ROOT>/../grc-config/config.php   (outside the app folder / usually outside web root)
 *  3. <APP_ROOT>/config/config.php          (fallback; protected by .htaccess)
 */
final class Config
{
    private static array $data = [];
    private static ?string $file = null;

    public static function candidates(): array
    {
        $list = [];
        $env = getenv('GRC_CONFIG_FILE');
        if ($env) {
            $list[] = $env;
        }
        $list[] = dirname(APP_ROOT) . '/grc-config/config.php';
        $list[] = APP_ROOT . '/config/config.php';
        return $list;
    }

    public static function load(): bool
    {
        foreach (self::candidates() as $f) {
            if (is_file($f) && is_readable($f)) {
                $data = require $f;
                if (is_array($data)) {
                    self::$data = $data;
                    self::$file = $f;
                    return true;
                }
            }
        }
        return false;
    }

    public static function file(): ?string
    {
        return self::$file;
    }

    public static function get(string $key, mixed $default = null): mixed
    {
        $cur = self::$data;
        foreach (explode('.', $key) as $part) {
            if (!is_array($cur) || !array_key_exists($part, $cur)) {
                return $default;
            }
            $cur = $cur[$part];
        }
        return $cur;
    }

    public static function set(array $data): void
    {
        self::$data = $data;
    }

    public static function storagePath(string $sub = ''): string
    {
        $base = (string)self::get('app.storage_path', APP_ROOT . '/storage');
        return rtrim($base, '/\\') . ($sub !== '' ? '/' . ltrim($sub, '/') : '');
    }

    /** Render a config array as PHP source. */
    public static function render(array $data): string
    {
        return "<?php\n// Generated by the GRC installer. Contains secrets: keep outside the public web root, never commit.\nreturn " . var_export($data, true) . ";\n";
    }
}
