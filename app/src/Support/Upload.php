<?php
declare(strict_types=1);

namespace App\Support;

use App\Core\Config;
use App\Core\Db;

/** Validated, non-public attachment storage. Files are stored under random names outside the web root. */
final class Upload
{
    public const MAX_BYTES = 5 * 1024 * 1024;

    /** ext => allowed detected MIME types */
    public const TYPES = [
        'pdf' => ['application/pdf'],
        'png' => ['image/png'],
        'jpg' => ['image/jpeg'],
        'jpeg' => ['image/jpeg'],
        'txt' => ['text/plain'],
        'docx' => ['application/vnd.openxmlformats-officedocument.wordprocessingml.document', 'application/zip', 'application/octet-stream'],
        'xlsx' => ['application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', 'application/zip', 'application/octet-stream'],
    ];

    public static function dir(): string
    {
        return Config::storagePath('uploads');
    }

    /** @return string|null error translation key, null if acceptable */
    public static function validate(array $f): ?string
    {
        if (($f['error'] ?? UPLOAD_ERR_NO_FILE) === UPLOAD_ERR_NO_FILE) {
            return 'upload.none';
        }
        if ($f['error'] === UPLOAD_ERR_INI_SIZE || $f['error'] === UPLOAD_ERR_FORM_SIZE) {
            return 'upload.too_big';
        }
        if ($f['error'] !== UPLOAD_ERR_OK || !is_uploaded_file($f['tmp_name'])) {
            return 'upload.failed';
        }
        if ($f['size'] > self::MAX_BYTES || $f['size'] <= 0) {
            return 'upload.too_big';
        }
        $ext = strtolower(pathinfo((string)$f['name'], PATHINFO_EXTENSION));
        if (!isset(self::TYPES[$ext])) {
            return 'upload.bad_type';
        }
        $mime = self::detect($f['tmp_name']);
        if (!in_array($mime, self::TYPES[$ext], true)) {
            return 'upload.bad_type';
        }
        if (in_array($ext, ['docx', 'xlsx'], true) && !self::looksLikeOoxml($f['tmp_name'])) {
            return 'upload.bad_type';
        }
        if ($ext === 'txt' && preg_match('/[\x00]/', (string)file_get_contents($f['tmp_name'], false, null, 0, 4096))) {
            return 'upload.bad_type';
        }
        return null;
    }

    private static function detect(string $path): string
    {
        $fi = new \finfo(FILEINFO_MIME_TYPE);
        return (string)$fi->file($path);
    }

    private static function looksLikeOoxml(string $path): bool
    {
        if (!class_exists(\ZipArchive::class)) {
            return true;
        }
        $z = new \ZipArchive();
        if ($z->open($path) !== true) {
            return false;
        }
        $ok = $z->locateName('[Content_Types].xml') !== false;
        $z->close();
        return $ok;
    }

    /** Store a validated upload. @return int attachment id */
    public static function store(array $f, string $entityType, int $entityId, int $userId): int
    {
        return self::save($f['tmp_name'], (string)$f['name'], (int)$f['size'], true, $entityType, $entityId, $userId);
    }

    /** Store a file that is already on the server (command-line imports); the source is copied, not moved. */
    public static function storeLocal(string $path, string $name, string $entityType, int $entityId, int $userId): int
    {
        return self::save($path, $name, (int)filesize($path), false, $entityType, $entityId, $userId);
    }

    private static function save(string $src, string $originalName, int $size, bool $uploaded, string $entityType, int $entityId, int $userId): int
    {
        $f = ['name' => $originalName, 'size' => $size];
        $ext = strtolower(pathinfo((string)$f['name'], PATHINFO_EXTENSION));
        $sub = date('Y') . '/' . date('m');
        $dir = self::dir() . '/' . $sub;
        if (!is_dir($dir) && !@mkdir($dir, 0750, true) && !is_dir($dir)) {
            throw new \RuntimeException('Cannot create upload directory');
        }
        $stored = $sub . '/' . bin2hex(random_bytes(16)) . '.bin';
        $target = self::dir() . '/' . $stored;
        $moved = $uploaded ? move_uploaded_file($src, $target) : copy($src, $target);
        if (!$moved) {
            throw new \RuntimeException('Cannot store upload');
        }
        @chmod($target, 0640);
        $name = preg_replace('/[\x00-\x1f\x7f\/\\\\]+/', '_', (string)$f['name']);
        $name = mb_substr($name, 0, 200);
        return Db::insert('attachments', [
            'entity_type' => $entityType,
            'entity_id' => $entityId,
            'original_name' => $name,
            'stored_name' => $stored,
            'mime_type' => self::TYPES[$ext][0],
            'size_bytes' => (int)$f['size'],
            'sha256' => hash_file('sha256', $target),
            'uploaded_by' => $userId,
            'created_at' => date('Y-m-d H:i:s'),
        ]);
    }

    public static function path(array $att): ?string
    {
        // stored_name is generated by us, but never trust DB content blindly.
        if (!preg_match('#^\d{4}/\d{2}/[0-9a-f]{32}\.bin$#', $att['stored_name'])) {
            return null;
        }
        $p = self::dir() . '/' . $att['stored_name'];
        return is_file($p) ? $p : null;
    }
}
