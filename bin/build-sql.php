<?php
declare(strict_types=1);

/**
 * Builds database/install.sql: all migrations concatenated, plus schema_migrations bookkeeping,
 * for importing via phpMyAdmin. Users are NOT created here (use the web setup for the first admin).
 */
define('APP_ROOT', dirname(__DIR__));
require APP_ROOT . '/app/bootstrap.php';

use App\Core\Migrator;

$out = "-- GRC platform: full install script (generated by bin/build-sql.php; do not edit).\n-- Import into an EMPTY database with phpMyAdmin, then open /setup to create the first administrator.\n";
$out .= "SET NAMES utf8mb4;\nSET FOREIGN_KEY_CHECKS = 0;\n\n";
foreach (Migrator::files() as $version => $path) {
    $out .= "-- ===== migration $version =====\n";
    foreach (Migrator::statements((string)file_get_contents($path)) as $stmt) {
        $out .= $stmt . ";\n\n";
    }
    $out .= "INSERT IGNORE INTO schema_migrations (version, applied_at) VALUES ('$version', NOW());\n\n";
}
$out .= "SET FOREIGN_KEY_CHECKS = 1;\n";
file_put_contents(APP_ROOT . '/database/install.sql', $out);
echo "Wrote database/install.sql (" . strlen($out) . " bytes)\n";
